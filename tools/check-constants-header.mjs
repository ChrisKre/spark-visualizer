#!/usr/bin/env node
// SAS-026 — "constants.generated.ts is never hand-edited" (docs/CONTRIBUTING.md). ESLint can't
// enforce this: eslint.config.mjs globally ignores `**/*.generated.ts`. Same shape as
// tools/lint-no-raw-hex.mjs: a plain Node script checking one thing, not a new lint-tool
// dependency.
import { readFileSync } from 'node:fs';

const PATH = 'packages/sim/calibration/constants.generated.ts';
const REQUIRED_HEADER = '// GENERATED by tools/capture/calibrate.py — do not edit by hand.';

const content = readFileSync(PATH, 'utf8');

if (!content.startsWith(REQUIRED_HEADER)) {
  console.error(
    `${PATH}: missing the required generated-file header.\n` +
      `Expected the file to start with:\n  ${REQUIRED_HEADER}\n` +
      'This file is written by tools/capture/calibrate.py — never hand-edit it (docs/CONTRIBUTING.md).'
  );
  process.exit(1);
}

console.log('check-constants-header: constants.generated.ts carries its generated header, clean.');
